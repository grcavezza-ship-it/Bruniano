import { db, send } from './_db.js';
import { requireAdmin } from './_auth.js';

const MAX_SLUG_LENGTH = 180;
const MAX_VISITOR_ID_LENGTH = 100;
const QUESTIONS = new Set(['useful', 'more']);
const VOTES = new Set(['yes', 'no']);

function clean(value, max = 500) {
  return String(value ?? '').trim().slice(0, max);
}

async function ensureFeedbackSchema(sql) {
  await sql`CREATE TABLE IF NOT EXISTS article_feedback (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_slug text NOT NULL,
    question text NOT NULL CHECK (question IN ('useful','more')),
    vote text NOT NULL CHECK (vote IN ('yes','no')),
    visitor_id text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(article_slug, question, visitor_id)
  )`;
  await sql`CREATE INDEX IF NOT EXISTS idx_article_feedback_slug ON article_feedback(article_slug)`;
  await sql`CREATE INDEX IF NOT EXISTS idx_article_feedback_created_at ON article_feedback(created_at)`;
}

export default async function handler(req, res) {
  try {
    res.setHeader('Cache-Control', 'no-store');
    const sql = db();
    const admin = String(req.query?.admin || '') === '1';

    if (admin) {
      const ctx = await requireAdmin(req, res);
      if (!ctx) return;
      await ensureFeedbackSchema(ctx.sql);
      if (req.method !== 'GET') return send(res, { error: 'Method not allowed' }, 405);
      const rows = await ctx.sql`
        SELECT
          f.article_slug,
          COALESCE(b.title, f.article_slug) AS title,
          COUNT(*) FILTER (WHERE f.question='useful' AND f.vote='yes')::int AS useful_yes,
          COUNT(*) FILTER (WHERE f.question='useful' AND f.vote='no')::int AS useful_no,
          COUNT(*) FILTER (WHERE f.question='more' AND f.vote='yes')::int AS more_yes,
          COUNT(*) FILTER (WHERE f.question='more' AND f.vote='no')::int AS more_no,
          COUNT(*)::int AS total_votes,
          MAX(f.created_at) AS last_vote_at
        FROM article_feedback f
        LEFT JOIN blog_posts b ON b.slug=f.article_slug
        GROUP BY f.article_slug, b.title
        ORDER BY MAX(f.created_at) DESC, f.article_slug ASC`;
      return send(res, { items: rows });
    }

    if (req.method !== 'POST') {
      res.setHeader('Allow', 'POST, GET');
      return send(res, { error: 'Method not allowed' }, 405);
    }

    const body = req.body || {};
    const slug = clean(body.slug, MAX_SLUG_LENGTH);
    const question = clean(body.question, 20);
    const vote = clean(body.vote, 10);
    const visitorId = clean(body.visitorId, MAX_VISITOR_ID_LENGTH);

    if (!slug || !QUESTIONS.has(question) || !VOTES.has(vote) || !visitorId) {
      return send(res, { error: 'Dati di valutazione non validi' }, 400);
    }

    await ensureFeedbackSchema(sql);

    const posts = await sql`SELECT 1 FROM blog_posts WHERE slug=${slug} AND is_published=true LIMIT 1`;
    if (!posts.length) return send(res, { error: 'Articolo non trovato' }, 404);

    const inserted = await sql`
      INSERT INTO article_feedback (article_slug, question, vote, visitor_id)
      VALUES (${slug}, ${question}, ${vote}, ${visitorId})
      ON CONFLICT (article_slug, question, visitor_id) DO NOTHING
      RETURNING id`;

    if (!inserted.length) return send(res, { ok: false, alreadyVoted: true }, 409);
    return send(res, { ok: true });
  } catch (error) {
    console.error('Article feedback API error:', error);
    return send(res, { error: 'Internal server error' }, 500);
  }
}
